/** Exercises the process adapters against real media generated by the installed FFmpeg toolchain. */
class RealMediaIntegrationTest {
    @TempDir Path tempDir;

    @BeforeEach
    void requireFfmpegToolchain() {
        assumeTrue(commandAvailable("ffmpeg") && commandAvailable("ffprobe"),
                "Real-media integration tests require ffmpeg and ffprobe on PATH");
    }

    @Test
    void probesMp4MovMkvAndAudioOnlySources() throws Exception {
        Path mp4 = tempDir.resolve("cfr-av.mp4");
        run(List.of("ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                "-f", "lavfi", "-i", "testsrc=size=160x90:rate=25:duration=1",
                "-f", "lavfi", "-i", "sine=frequency=1000:sample_rate=48000:duration=1",
                "-c:v", "mpeg4", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", mp4.toString()));

        Path mov = tempDir.resolve("remux.mov");
        run(List.of("ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", mp4.toString(), "-c", "copy", mov.toString()));
        Path mkv = tempDir.resolve("remux.mkv");
        run(List.of("ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", mp4.toString(), "-c", "copy", mkv.toString()));
        Path audio = tempDir.resolve("audio-only.m4a");
        run(List.of("ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i",
                "sine=frequency=440:sample_rate=48000:duration=1", "-c:a", "aac", audio.toString()));

        FfprobeMediaProbe probe = new FfprobeMediaProbe();
        var mp4Info = probe.probe(MediaProbeRequest.defaults(mp4.toUri()));
        assertEquals(2, mp4Info.streams().size());
        var video = mp4Info.streams().stream().filter(s -> s.type() == MediaStreamType.VIDEO).findFirst().orElseThrow();
        var sound = mp4Info.streams().stream().filter(s -> s.type() == MediaStreamType.AUDIO).findFirst().orElseThrow();
        assertEquals(new FrameRate(25, 1), video.averageFrameRate().orElseThrow());
        assertTrue(video.timeBase().isPresent());
        assertTrue(sound.sampleRate().isPresent());

        assertEquals(2, probe.probe(MediaProbeRequest.defaults(mov.toUri())).streams().size());
        assertEquals(2, probe.probe(MediaProbeRequest.defaults(mkv.toUri())).streams().size());
        var audioInfo = probe.probe(MediaProbeRequest.defaults(audio.toUri()));
        assertEquals(1, audioInfo.streams().size());
        assertEquals(MediaStreamType.AUDIO, audioInfo.streams().getFirst().type());
    }

    @Test
    void verifiesVariableFrameTimestampsAndExtractsARealFrame() throws Exception {
        Path vfr = tempDir.resolve("variable-rate.mkv");
        run(List.of("ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                "-f", "lavfi", "-i", "testsrc=size=160x90:rate=30:duration=1",
                "-vf", "select=eq(n,0)+eq(n,1)+eq(n,4)+eq(n,5)+eq(n,11)+eq(n,12)+eq(n,20)",
                "-fps_mode", "vfr", "-c:v", "mpeg4", "-pix_fmt", "yuv420p", vfr.toString()));

        var result = new FfprobeMediaProbe().probe(MediaProbeRequest.defaults(vfr.toUri()));
        assertEquals(1, result.streams().size());
        assertEquals(MediaStreamType.VIDEO, result.streams().getFirst().type());

        String frameOutput = run(List.of("ffprobe", "-v", "error", "-select_streams", "v:0",
                "-show_entries", "frame=best_effort_timestamp", "-of", "csv=p=0", vfr.toString()));
        List<Long> pts = frameOutput.lines().filter(line -> !line.isBlank())
                .map(line -> Long.parseLong(line.split(",", 2)[0].trim())).toList();
        assertTrue(pts.size() >= 5, "VFR fixture should contain several decoded frames");
        List<Long> gaps = new ArrayList<>();
        for (int i = 1; i < pts.size(); i++) gaps.add(pts.get(i) - pts.get(i - 1));
        assertTrue(gaps.stream().distinct().count() > 1, "VFR fixture must have non-uniform frame timestamp gaps");

        Path framePath = tempDir.resolve("extracted.png");
        FrameArtifact artifact = new FfmpegFrameExtractor().extract(new FrameExtractionRequest(
                vfr.toUri(), result.streams().getFirst().index(),
                new MediaTimestamp(367, RationalTimeBase.of(1, 1_000)), framePath,
                FrameImageFormat.PNG, Duration.ofSeconds(10), 2 * 1024 * 1024));
        assertTrue(Files.isRegularFile(framePath));
        assertEquals(160, artifact.width());
        assertEquals(90, artifact.height());
        assertEquals(367, artifact.requestedPosition().ticks());
    }

    @Test
    void mapsMalformedMediaToStructuredProbeFailure() throws Exception {
        Path malformed = Files.writeString(tempDir.resolve("malformed.mp4"), "not a media container", StandardCharsets.UTF_8);
        MediaProbeException failure = assertThrows(MediaProbeException.class,
                () -> new FfprobeMediaProbe().probe(MediaProbeRequest.defaults(malformed.toUri())));
        assertEquals(MediaProbeException.Code.PROBE_FAILED, failure.code());
        assertEquals(FfprobeMediaProbe.BACKEND_ID, failure.backendId().orElseThrow());
    }

    private static boolean commandAvailable(String command) {
        try {
            Process process = new ProcessBuilder(command, "-version").redirectErrorStream(true)
                    .redirectOutput(ProcessBuilder.Redirect.DISCARD).start();
            return process.waitFor(5, TimeUnit.SECONDS) && process.exitValue() == 0;
        } catch (IOException exception) {
            return false;
        } catch (InterruptedException exception) {
            Thread.currentThread().interrupt();
            return false;
        }
    }

    private static String run(List<String> command) throws Exception {
        Process process = new ProcessBuilder(command).redirectErrorStream(true).start();
        if (!process.waitFor(30, TimeUnit.SECONDS)) {
            process.descendants().forEach(ProcessHandle::destroyForcibly);
            process.destroyForcibly();
            throw new IOException("Command timed out: " + command.getFirst());
        }
        String output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        if (process.exitValue() != 0) {
            throw new IOException("Command failed (" + process.exitValue() + "): " + String.join(" ", command) + "\n" + output);
        }
        return output;
    }
}
